"""Generate embedded/mel_tables.h from the Python front-end config so the C
implementation uses bit-identical filterbank weights and window.

    python embedded/gen_tables.py [--config configs/default.yaml]
"""
import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from roomest.config import load_config  # noqa: E402
from roomest.features import FeatureConfig, _window, mel_filterbank  # noqa: E402


def arr(name, a, ctype="float"):
    body = ",\n  ".join(", ".join(f"{v:.9e}f" if ctype == "float" else str(int(v)) for v in a[i:i + 6])
                        for i in range(0, len(a), 6))
    return f"static const {ctype} {name}[{len(a)}] = {{\n  {body}\n}};\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/default.yaml")
    fc = FeatureConfig.from_cfg(load_config(ap.parse_args().config))
    fb = mel_filterbank(fc)
    # sparse storage: each triangle as (first_bin, n_bins, weights...)
    starts, lens, weights = [], [], []
    for row in fb:
        nz = np.nonzero(row)[0]
        starts.append(nz[0]), lens.append(len(nz)), weights.extend(row[nz[0]:nz[-1] + 1])
    out = [
        "/* AUTO-GENERATED by embedded/gen_tables.py - do not edit. */",
        "#ifndef MEL_TABLES_H\n#define MEL_TABLES_H\n#include <stdint.h>",
        f"#define LM_FS {fc.fs}\n#define LM_NFFT {fc.n_fft}\n#define LM_WIN {fc.win}\n#define LM_HOP {fc.hop}",
        f"#define LM_NMELS {fc.n_mels}\n#define LM_NWEIGHTS {len(weights)}\n",
        arr("LM_WINDOW", _window(fc).astype(np.float32)),
        arr("LM_MEL_START", np.array(starts), "uint16_t"),
        arr("LM_MEL_LEN", np.array(lens), "uint16_t"),
        arr("LM_MEL_W", np.array(weights, dtype=np.float32)),
        "#endif",
    ]
    path = Path(__file__).parent / "mel_tables.h"
    path.write_text("\n".join(out))
    print(f"wrote {path} ({len(weights)} non-zero filterbank weights vs {fb.size} dense)")


if __name__ == "__main__":
    main()
